`timescale 1ns/1ps
module tb_bmp_header;
    reg clk=0,rst=1,start=0,bv=0,finish=0;
    always #5 clk=~clk;
    reg [7:0] data=0,header[0:53];
    reg [31:0] actual=160;
    wire done,ok;wire [12:0] w,h;wire [31:0] off,stride,last;
    integer i,n;
    reg gs=0;reg [1:0] mode=0;wire gd,gok;
    wire [15:0] rw,rh,left,bottom;
    reg [12:0] gw=64,gh=5;reg [15:0] tw=32,th=18;
    bmp_header_parser dut(.clk(clk),.rst(rst),.start(start),.byte_valid(bv),.byte_data(data),
        .finish(finish),.actual_size(actual),.done(done),.ok(ok),.width(w),.height(h),
        .pixel_offset(off),.row_stride(stride),.payload_end(last));
    image_scale_geometry geometry(.clk(clk),.rst(rst),.start(gs),.src_w(gw),.src_h(gh),
        .dst_w(tw),.dst_h(th),.mode(mode),.done(gd),.ok(gok),
        .scaled_w(rw),.scaled_h(rh),.left(left),.bottom(bottom));
    task put32;input integer at;input [31:0] v;begin
        header[at]=v[7:0];header[at+1]=v[15:8];header[at+2]=v[23:16];header[at+3]=v[31:24];
    end endtask
    task base;begin
        for(i=0;i<54;i=i+1)header[i]=0;
        header[0]="B";header[1]="M";put32(2,160);put32(10,54);put32(14,40);
        put32(18,5);put32(22,5);header[26]=1;header[28]=24;actual=160;
    end endtask
    task check;input wanted;input integer bytes;begin
        @(negedge clk);start=1;@(negedge clk);start=0;
        for(i=0;i<bytes;i=i+1) begin bv=1;data=header[i];@(negedge clk);end
        bv=0;finish=1;@(negedge clk);finish=0;wait(done);
        if(ok!==wanted) $fatal(1,"header case=%0d ok=%b expected=%b",n,ok,wanted);
    end endtask
    task check_geometry;
        input [12:0] sw,sh;input [15:0] dw,dh,ew,eh,el,eb;
        begin
            @(negedge clk);gw=sw;gh=sh;tw=dw;th=dh;mode=0;gs=1;
            @(negedge clk);gs=0;wait(gd);
            if(!gok || rw!=ew || rh!=eh || left!=el || bottom!=eb)
                $fatal(1,"geometry %0dx%0d to %0dx%0d: got %0dx%0d left=%0d bottom=%0d",sw,sh,dw,dh,rw,rh,left,bottom);
        end
    endtask
    initial begin
        repeat(4)@(negedge clk);rst=0;
        for(n=0;n<19;n=n+1) begin
            base;
            case(n)
                1: header[0]=0;
                2: put32(14,39);
                3: header[26]=2;
                4: header[28]=32;
                5: put32(30,32'h01000000);
                6: put32(18,0);
                7: put32(18,4097);
                8: put32(22,0);
                9: put32(22,32'hfffffffb);
                10: put32(22,4097);
                11: put32(10,53);
                12: put32(14,108); // Extended header overlaps pixels.
                13: put32(2,133); // Missing one pixel byte.
                14: actual=159;
                15: put32(10,32'hfffffff0); // Offset + payload cannot wrap.
                16: begin put32(18,4096);put32(22,4096);put32(2,50331702);actual=50331702;end
                17: ;
                18: begin put32(14,108);put32(10,122);put32(2,256);actual=256;end
            endcase
            check(n==0 || n==16 || n==18,n==17 ? 53:54);
        end
        for(n=0;n<4;n=n+1) begin
            @(negedge clk);mode=n;gs=1;@(negedge clk);gs=0;wait(gd);
            if(gok!==(n==0)) $fatal(1,"unsupported mode accepted");
            if(n==0 && (rw!=32 || rh!=2 || bottom!=8)) $fatal(1,"ties-to-even 2.5 geometry");
        end
        // Constants generated by the independent Fraction/ties-to-even oracle.
        check_geometry(1280,720,1280,720,1280,720,0,0);
        check_geometry(640,480,1280,720,960,720,160,0);
        check_geometry(1920,1080,1280,720,1280,720,0,0);
        check_geometry(3840,2160,1280,720,1280,720,0,0);
        check_geometry(1000,1000,1280,720,720,720,280,0);
        check_geometry(720,1280,1280,720,405,720,437,0);
        check_geometry(1365,767,1280,720,1280,719,0,1);
        check_geometry(4096,4096,1280,720,720,720,280,0);
        check_geometry(4096,1,1280,720,1280,1,0,360);
        check_geometry(1,4096,1280,720,1,720,639,0);
        check_geometry(1,1,1280,720,720,720,280,0);
        check_geometry(3,5,1280,720,432,720,424,0);
        check_geometry(4,5,1280,720,576,720,352,0);
        check_geometry(5,5,1280,720,720,720,280,0);
        check_geometry(6,5,1280,720,864,720,208,0);
        check_geometry(40,17,1280,720,1280,544,0,88);
        check_geometry(17,40,1280,720,306,720,487,0);
        check_geometry(1,1,65535,65535,65535,65535,0,0);
        check_geometry(4096,1,65535,16,65535,16,0,0);
        check_geometry(1,4096,65535,65535,16,65535,32759,0);
        check_geometry(4096,1,65535,65535,65535,16,0,32760);
        $display("*** PASS *** header format/dimensions/truncation/overflow and unsupported scale modes/ties-to-even");$finish;
    end
    initial begin #1000000;$fatal(1,"header watchdog");end
endmodule
