"""Generate native pixel coverage from bundled DejaVu outlines (Pillow required).

No nearest-neighbour enlargement: rasterize at 8x, area-average, quantize to
0, 1/3, 2/3, 1 coverage. Generated HDL carries its own ROM initialization;
neither TD nor a copied render project needs Python, a TTF or external .mem.
"""
from pathlib import Path
import argparse
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONT = Path(__file__).parent / 'fonts/DejaVuSansMono-Bold.ttf'
OUT = ROOT / 'render/rtl/ui'
SS = 8


def raster(code, w=10, h=14, size=15, baseline=11):
    font = ImageFont.truetype(str(FONT), size * SS)
    im = Image.new('L', (w * SS, h * SS))
    advance = font.getlength(chr(code))
    ImageDraw.Draw(im).text(((w * SS - advance) / 2, baseline * SS),
                           chr(code), font=font, fill=255, anchor='ls')
    im = im.resize((w, h), Image.Resampling.BOX)
    return [(im.getpixel((x,y)) * 3 + 127) // 255 for y in range(h) for x in range(w)]


def row_function(name, codes, w, h, size, baseline):
    lines = [f'// Generated by generate-aa-font.py; native {w}x{h}, 2-bit coverage.',
             f'function [{w*2-1}:0] {name};',
             '    input [6:0] code;', '    input [4:0] row;',
             '    begin', '        case ({code,row})']
    for code in codes:
        pixels = raster(code, w, h, size, baseline)
        for y in range(h):
            value = sum(pixels[y*w+x] << (x*2) for x in range(w))
            if value:
                lines.append(f"        12'd{code*32+y}: {name} = {w*2}'h{value:0{(w*2+3)//4}x};")
    lines += [f"        default: {name} = {w*2}'d0;", '        endcase', '    end', 'endfunction', '']
    return '\n'.join(lines)


def bram32_instance(words, address, output, clock, instance, second=False):
    assert len(words)<=2048
    packed=sum(word << (16*index) for index,word in enumerate(words))
    lines=['EG_PHY_BRAM32K #(',
           '    .MODE("DP16K"),.DATA_WIDTH_A("16"),.DATA_WIDTH_B("16"),',
           '    .REGMODE_A("NOREG"),.REGMODE_B("NOREG"),']
    for page in range(128):
        value=(packed>>(page*256)) & ((1<<256)-1)
        lines.append(f"    .INIT_{page:02X}(256'h{value:064x}){',' if page<127 else ''}")
    lines += [f') {instance} (',
              f'    .clka({clock}),.addra({address}),.doa({output}),',
              "    .dia(16'd0),.bytea(1'b0),.bytewea(1'b0),.csa(1'b1),.wea(1'b0),.rsta(1'b0),.ocea(1'b1),",
              f"    .clkb({clock}),.addrb(11'd0),.dob(),.dib(16'd0),",
              "    .byteb(1'b0),.byteweb(1'b0),.csb(1'b0),.web(1'b0),.rstb(1'b0),.oceb(1'b0)",
              ');']
    if second:
        lines=[line.replace(".addrb(11'd0),.dob()", ".addrb(pixel_address_b[13:3]),.dob(font_word_b)")
                   .replace(".csb(1'b0)", ".csb(SECOND_PORT != 0)")
                   .replace(".oceb(1'b0)", ".oceb(1'b1)") for line in lines]
    return lines


def diagnostic_rom():
    codes=sorted(set(map(ord,'0123456789EROWAITDLNK')))
    glyph_ids={code:index+1 for index,code in enumerate(codes)}
    words=[0]*2048
    for code in codes:
        pixels=raster(code,15,21,24,19)
        for y in range(21):
            for x in range(15):
                words[glyph_ids[code]*64+y*2+x//8] |= pixels[y*15+x] << ((x%8)*2)
    lines=['// Native 15x21 coverage; one initialized 32 Kbit primitive, no LUT row dictionary.']
    lines += ["localparam [4:0] DIAG_SPACE=5'd0;"]
    lines += [f"localparam [4:0] DIAG_{chr(code)}=5'd{glyph_ids[code]};" for code in codes]
    lines += ['wire [10:0] diag_address={glyph_s,dy_s,gx_s[3]};',
              'wire [15:0] diagnostic_word;']
    lines += bram32_instance(words,'diag_address','diagnostic_word','video_clk','u_diag_bram32')
    return '\n'.join(lines)+'\n'


def generate():
    atlas = [v for c in range(32, 127) for v in raster(c)]
    words=[sum(v << (2*i) for i,v in enumerate(atlas[start:start+8]))
           for start in range(0,len(atlas),8)]
    lines = ['// Generated native 10x14 AA ASCII; see tools/dual-board/fonts/LICENSE.txt.',
             '// One explicitly initialized 32 Kbit ROM; eight coverage pixels per word.',
             'module font_rom #(parameter SECOND_PORT=0)(input wire clk, input wire [6:0] char_code,',
             '    input wire [3:0] gx,gy, output wire [1:0] alpha,',
             '    input wire [6:0] char_code_b,input wire [3:0] gx_b,gy_b,output wire [1:0] alpha_b);',
             "    wire [6:0] code_index=char_code-7'd32;",
             '    wire [13:0] code_base=({7\'d0,code_index}<<7)+({7\'d0,code_index}<<3)+({7\'d0,code_index}<<2);',
             "    wire [7:0] row_base={4'd0,gy}*8'd10;",
             "    wire [13:0] pixel_address=code_base+{6'd0,row_base}+{10'd0,gx};",
             '    wire [15:0] font_word;',
             '    reg [2:0] pixel_q;reg valid_q;',
             '    always @(posedge clk) begin',
             '        pixel_q<=pixel_address[2:0];',
             '        valid_q<=char_code>=32 && char_code<=126 && gx<10 && gy<14;',
             '    end']
    lines += ["    wire [6:0] code_index_b=char_code_b-7'd32;",
              "    wire [13:0] pixel_address_b=({7'd0,code_index_b}<<7)+({7'd0,code_index_b}<<3)+({7'd0,code_index_b}<<2)+{10'd0,gx_b}+{10'd0,gy_b}*14'd10;",
              "    wire [15:0] font_word_b;reg [2:0] pixel_b_q;reg valid_b_q;",
              "    always @(posedge clk) begin",
              "        pixel_b_q<=pixel_address_b[2:0];",
              "        valid_b_q<=SECOND_PORT && char_code_b>=32 && char_code_b<=126 && gx_b<10 && gy_b<14;",
              "    end",
              "    assign alpha_b=valid_b_q ? font_word_b[{pixel_b_q,1'b0} +: 2]:2'd0;"]
    lines += bram32_instance(words,'pixel_address[13:3]','font_word','clk','u_ascii_bram32',second=True)
    lines += ["    assign alpha=valid_q ? font_word[{pixel_q,1'b0} +: 2]:2'd0;",'endmodule','']
    generated = {
        'font_rom.v': '\n'.join(lines),
        'font_audio_rows.vh': row_function('audio_font_row', range(47, 59), 10, 14, 15, 11),
        'font_diag_rows.vh': diagnostic_rom(),
    }
    for name, body in generated.items():
        target=OUT/name
        if not target.exists() or target.read_text(encoding='utf-8')!=body:
            target.write_text(body, encoding='utf-8', newline='\n')
    evidence = ROOT / 'render/sim/aa-font'
    evidence.mkdir(parents=True, exist_ok=True)
    (evidence/'atlas.hex').write_text(''.join(f'{v:x}\n' for v in atlas), encoding='ascii')
    diagnostic_atlas=[v for c in range(32,127) for v in raster(c,15,21,24,19)]
    (evidence/'diagnostic.hex').write_text(''.join(f'{v:x}\n' for v in diagnostic_atlas), encoding='ascii')
    (evidence/'metadata.json').write_text(json.dumps({
        'font_sha256': hashlib.sha256(FONT.read_bytes()).hexdigest(),
        'supersampling': SS, 'coverage': [0, 85, 170, 255],
        'printable_ascii': [32, 126], 'glyph': [10, 14], 'cell': [12, 16],
        'font_size': 15, 'baseline': 11,
        'ascii_bram32k':1,'diagnostic_bram32k':1,
        'diagnostic_glyph': [15, 21], 'diagnostic_font_size': 24, 'diagnostic_baseline': 19,
        'hdls': {k: hashlib.sha256(v.encode()).hexdigest() for k, v in generated.items()},
    }, indent=2)+'\n', encoding='utf-8')
    assert all(v == 0 for v in atlas[:140])
    assert all(any(atlas[(c-32)*140:(c-31)*140]) for c in range(33,127))
    assert set(atlas) == {0,1,2,3}
    print('Generated native AA ASCII, audio and diagnostic fonts; all 95 ASCII entries checked.')


if __name__ == '__main__':
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
