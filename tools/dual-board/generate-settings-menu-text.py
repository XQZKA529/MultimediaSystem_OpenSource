"""Generate the shared synchronous settings/subtitle BRAM9K character ROM."""
import json
from pathlib import Path
from runpy import run_path

root = Path(__file__).resolve().parents[2]
directory = root / 'media/rtl/ui'
rows = json.loads((directory / 'settings_menu_text.json').read_text(encoding='utf-8'))
status_rows = ['READY', 'LOADING...', 'TRUNCATED (256)', 'FIRST LINE ONLY',
               'NO MATCHING TXT', 'FORMAT ERROR', 'READ/APPLY ERROR',
               'NAME UNSUPPORTED', 'AMBIGUOUS NAME', 'APPLYING...']

# Rows up to 16 characters occupy one 16-byte slot. Longer rows keep their
# existing 32-column behavior. Sharing remains global across all menu pages.
unique = ['']
indices = {}
for key, text in rows.items():
    if len(text) > 32:
        raise ValueError(f'{key}: menu row exceeds 32 columns')
    text = text.rstrip()
    if text not in unique:
        unique.append(text)
    indices[key] = unique.index(text)

slots = []
for text in unique:
    wide = len(text) > 16
    slots.append((sum(2 if len(previous) > 16 else 1
                      for previous in unique[:unique.index(text)]), wide))

def slot_for(text):
    index = unique.index(text)
    return slots[index]

text_bytes = sum(32 if len(text) > 16 else 16 for text in unique)
status_base = (text_bytes + 15) & ~15
used = status_base + len(status_rows) * 16
if used > 1024:
    raise ValueError(f'menu and subtitle status rows need {used}/1024 bytes')

out = [
    '// Generated by tools/dual-board/generate-settings-menu-text.py.',
    '// Shared, packed 16/32-column rows and subtitle status text.',
    'module settings_menu_text_rom(input wire clk,input wire [3:0] page,',
    ' input wire status_bank,input wire [1:0] mode,input wire [3:0] row,',
    ' input wire [4:0] col,output wire [7:0] data);',
    ' reg [5:0] row_slot;reg row_wide;',
    ' always @(*) begin row_slot=0;row_wide=0;case({page,row})',
]
for key in rows:
    page, row = map(int, key.split(','))
    slot, wide = slot_for(rows[key].rstrip())
    out.append(f"  8'd{page*16+row}:begin row_slot=6'd{slot};row_wide=1'b{int(wide)};end")
out += [
    '  default:begin row_slot=0;row_wide=0;end endcase',
    '  if(page==2 && row==5) case(mode)',
]
for mode in range(3):
    slot, wide = slot_for(rows[f'0,{mode}'].rstrip())
    out.append(f"   2'd{mode}:begin row_slot=6'd{slot};row_wide=1'b{int(wide)};end")
out += [
    '   default:begin row_slot=0;row_wide=0;end endcase end',
    f" wire [9:0] status_addr=10'd{status_base}+{{row<10 ? row:4'd0,col[3:0]}};",
    " wire [9:0] text_addr={row_slot,4'b0000}|(row_wide ? {5'd0,col}: {6'd0,col[3:0]});",
    " wire use_status_bank=(status_bank===1'b1) || ((status_bank!==1'b0) && page==6);",
    ' wire [9:0] address_next=use_status_bank ? status_addr:text_addr;',
    ' reg [9:0] address;reg status_blank_pending,status_blank;',
    " always @(posedge clk) begin address<=address_next;status_blank_pending<=(use_status_bank || !row_wide) && col[4];status_blank<=status_blank_pending;end",
    '`ifdef DB_BEHAVIORAL_RAM',
    " reg [7:0] rom[0:1023];reg [7:0] q;assign data=status_blank ? 8'd32:q;",
    ' integer i;initial begin for(i=0;i<1024;i=i+1) rom[i]=8\'d32;',
]
image = []
for text in unique:
    image.extend(ord(c) for c in text.ljust(32 if len(text) > 16 else 16))
image.extend([32] * (status_base - len(image)))
for text in status_rows:
    image.extend(ord(c) for c in text.ljust(16))
image += [32] * (1024 - len(image))
for i, char in enumerate(image):
    if char != 32:
        out.append(f"  rom[{i}]=8'd{char};")
out += [' end',' always @(posedge clk) q<=rom[address];','`else',
        " wire [8:0] q;assign data=status_blank ? 8'd32:q[7:0];",
        ' EG_PHY_BRAM #(.MODE("DP8K"),.DATA_WIDTH_A("9"),.DATA_WIDTH_B("9"),.GSR("DISABLE"),']
for block in range(32):
    value = sum(image[block*32+j] << (8*j) for j in range(32))
    out.append(f" .INIT_{block:02X}(256'h{value:064x})" + (',' if block < 31 else ') u_rom('))
out += [" .clka(clk),.cea(1'b1),.ocea(1'b1),.rsta(1'b0),.wea(1'b0),.csa(3'b111),.addra({address,3'b000}),.dia(9'd0),.doa(q),",
        " .clkb(clk),.ceb(1'b0),.oceb(1'b0),.rstb(1'b0),.web(1'b0),.csb(3'b000),.addrb(13'd0),.dib(9'd0),.dob());",
        '`endif','endmodule','']
(directory / 'settings_menu_text_rom.v').write_text('\n'.join(out), encoding='utf-8')
run_path(str(Path(__file__).with_name('generate-media-menu-decode.py')))['apply'](root / 'media')
print(f'Menu ROM: {len(unique)} unique rows, {used}/1024 bytes including subtitle statuses')
