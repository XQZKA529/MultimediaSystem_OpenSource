            cx=x_cnt-11'd408;cy=y_cnt-11'd176;row=cy[8:5];
            // Browser row 0 is a file; other list pages reserve it for a title.
            select_row=cur_en_s && cur_row_s==row && (ui_page_s==0 || row>0) && row<8;
            if(x_cnt>=440 && x_cnt<824 && y_cnt>=176 && y_cnt<432 && cy[4:0]<16) begin
                mapped_text=1;tx=x_cnt-11'd440;ty=cy[3:0];
            end
            if(row>0 && row<8) begin ix=(x_cnt-11'd410)<<2;iy=({6'd0,cy[4:0]}-11'd3)<<2;end
