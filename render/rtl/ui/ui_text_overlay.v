    output reg [23:0] pix_out,output wire hs_out,vs_out,de_out,
    input wire [3:0] brightness_level,output reg [3:0] brightness_frame,
    input wire [4:0] contrast_level,volume_level,saturation_level,input wire osd_enabled,
    input wire text_osd_page,input wire [3:0] ui_page,
    output wire ui_active_frame,text_osd_page_frame,output wire [3:0] ui_page_frame,
    input wire ui_active,ui_commit_toggle,input wire [3:0] cursor_row,
    input wire cursor_en,wr_clk,wr_en,input wire [ADDR_W-1:0] wr_addr,
    input wire [7:0] wr_data,output wire dbg_commit_seen,
    output wire [6:0] font_char,output wire [3:0] font_x,font_y,
    input wire [1:0] font_alpha
);
