    function clipped;
        input [10:0] x,y,w,h;input [4:0] corner;
        reg [11:0] xr,yr;
        begin
            xr={1'b0,w}-12'd1-{1'b0,x};yr={1'b0,h}-12'd1-{1'b0,y};
            clipped=x<w && y<h && ({1'b0,x}+{1'b0,y})>=corner &&
                ({1'b0,x}+yr)>=corner && (xr+{1'b0,y})>=corner && (xr+yr)>=corner;
        end
    endfunction

