        // floor(43*x/128) is exactly floor(x/3), including all carry bits.
        begin a={6'd0,x};q=(a<<5)+(a<<3)+(a<<1)+a;compact_label_x={2'd0,x}+{3'd0,q[12:7]};end
    endfunction
