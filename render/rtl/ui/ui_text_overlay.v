                mapped_text=1;tx=card_dx-value_left;
                case(card_id) 1:value_kind=1;2:value_kind=2;3:value_kind=5;4:value_kind=4;default:value_kind=3;endcase
            end
        end else if((ui_page_s>=2 && ui_page_s<=4) || ui_page_s==9) begin
            px=x_cnt-11'd336;py=y_cnt-11'd176;panel_w=608;panel_h=368;
