// Page-aware neutral glass compositor; six matched stream registers.
// Geometry, palette, shared glyph read, glass and coverage have separate stages.
// The original 288-byte double-bank text store and frame commit remain intact.
module ui_text_overlay #(
    parameter [10:0] WIN_X0=446,WIN_Y0=286,
    parameter integer SCALE=2,COLS=32,LINES=9,ADDR_W=9,
    parameter integer EXTERNAL_FONT=0,ICON_W=28
