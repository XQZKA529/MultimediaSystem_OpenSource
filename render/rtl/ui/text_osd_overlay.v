// One font instance serves the mutually exclusive editor and user text line.
// Five stages: coordinates, character index, byte lookup, synchronous font.
// Pixel and HS/VS/DE include a final blend-arithmetic stage, including bypass.
module text_osd_overlay #(
    parameter [10:0] WIN_X0=`VBP_WIN_X0, WIN_Y0=`VBP_WIN_Y0,
    parameter [10:0] SCREEN_W=`VBP_H_ACTIVE, TEXT_Y=11'd64,
    parameter integer EXTERNAL_FONT=0
)(
    input wire clk,rst,hs,vs,de,input wire [23:0] pix_in,
    input wire ui_active_frame,text_osd_page_frame,diag_show,banner_source,
    input wire [`TEXT_OSD_META_W-1:0] view,input wire banner_reset,
    output wire [7:0] text_addr,input wire [7:0] text_data,
    output wire hs_out,vs_out,de_out,output reg [23:0] pix_out,
    output wire [6:0] font_char,output wire [3:0] font_x,font_y,
    input wire [1:0] font_alpha
);
    localparam [23:0] C_BORDER=24'hD6DBE1,C_BG=24'h14171B,
                      C_CURSOR=24'h3A3F46,C_TEXT=24'hF5F7FA,
                      C_SHADOW=24'h20252C;
    wire [`TEXT_OSD_LEN_W-1:0] text_len=view[`TEXT_OSD_VIEW_LEN];
    wire [4:0] focus=view[`TEXT_OSD_VIEW_FOCUS];
    wire osd_enable=view[`TEXT_OSD_VIEW_ENABLE];
    reg [10:0] x,y;reg de_d,vs_d;
    always @(posedge clk or posedge rst) begin
        if(rst) begin x<=0;y<=0;de_d<=0;vs_d<=0;end
        else begin
            de_d<=de;vs_d<=vs;
            if(vs && !vs_d) y<=0;else if(!de && de_d) y<=y+1'b1;
            if(!de) x<=0;else x<=x+1'b1;
        end
    end
    wire editor=ui_active_frame && text_osd_page_frame;
    wire banner=!ui_active_frame && !diag_show && osd_enable && text_len!=0;
    wire win=editor && x>=WIN_X0 && x<WIN_X0+388 && y>=WIN_Y0 && y<WIN_Y0+148;
    wire txt=editor && x>=WIN_X0+2 && x<WIN_X0+386 && y>=WIN_Y0+2 && y<WIN_Y0+146;
    localparam [10:0] BANNER_X0=(SCREEN_W*15)/100;
    localparam [10:0] BANNER_W=(SCREEN_W*70)/100;
    reg [11:0] banner_width;
    reg [10:0] banner_x;
    reg [`TEXT_OSD_LEN_W-1:0] preview_start,visible_len;
    reg [23:0] count_characters;
    reg [11:0] scroll_offset;
    reg [6:0] scroll_hold;
    reg scroll_divider,was_banner,source_d;
    wire long_banner=text_len>74;
    wire banner_visible=banner && long_banner;
    wire [11:0] total_text_width={text_len,2'b00}+{text_len,3'b000};
    wire [11:0] max_scroll=total_text_width-BANNER_W;
    // The CDC view changes only during VS blanking. Prepare layout independently
    // of the pixel path so index arithmetic and the byte mux do not form one
    // long path; values settle before the next active scanline.
    always @(posedge clk or posedge rst) begin
        if(rst) begin banner_width<=0;banner_x<=SCREEN_W>>1;preview_start<=0;visible_len<=0;count_characters<={"0","0","0"};end
        else begin
            banner_width<=long_banner ? BANNER_W:total_text_width;
            banner_x<=long_banner ? BANNER_X0:(SCREEN_W-total_text_width)>>1;
            preview_start<=text_len>29 ? text_len-29:0;
            visible_len<=text_len>29 ? 29:text_len;
            count_characters[23:16]<="0"+text_len/100;
            count_characters[15:8]<="0"+(text_len/10)%10;
            count_characters[7:0]<="0"+text_len%10;
        end
    end
    wire new_banner=!was_banner && banner;
    always @(posedge clk or posedge rst) begin
        if(rst) begin scroll_offset<=0;scroll_hold<=0;scroll_divider<=0;was_banner<=0;source_d<=0;end
        else begin
            was_banner<=banner;source_d<=banner_source;
            if(banner_reset===1'b1 || new_banner || (banner && banner_source!=source_d)) begin scroll_offset<=0;scroll_hold<=0;scroll_divider<=0;end
            else if(vs && !vs_d && banner_visible) begin
                if(scroll_offset>=max_scroll) begin
                    scroll_divider<=0;
                    if(scroll_hold<61) scroll_hold<=scroll_hold+1'b1;
                    else begin scroll_offset<=0;scroll_hold<=0;end
                end else if(scroll_hold<61) begin
                    scroll_hold<=scroll_hold+1'b1;
                    if(scroll_hold==60) scroll_divider<=1;
                end
                else if(!scroll_divider) scroll_divider<=1;
                else begin
                    scroll_divider<=0;
                    scroll_offset<=scroll_offset+1'b1;
                    if(scroll_offset+1'b1>=max_scroll) scroll_hold<=0;
                end
            end
        end
    end
    wire line= banner && x>=banner_x && x<banner_x+banner_width && y>=TEXT_Y && y<TEXT_Y+16;
    wire [11:0] banner_dx=line ? x-banner_x:12'd0;
    wire [11:0] dx=txt ? x-(WIN_X0+2):line ? (long_banner ? banner_dx+scroll_offset:banner_dx):12'd0;
    wire [10:0] dy=txt ? y-(WIN_Y0+2):line ? y-TEXT_Y:11'd0;
// floor(dx/12) = floor((dx >> 2)/3). A synchronous quotient/remainder
    // table fits the existing coordinate stage and preserves every pixel.
    reg [10:0] div12_rom[0:1023] /* fehdl force_ram=1, ram_style="bram" */;
    reg [10:0] div12_q;
    reg [1:0] dx_low_a;
    integer div_i;
    initial for(div_i=0;div_i<1024;div_i=div_i+1)
        div12_rom[div_i]=((div_i/3)<<2)|(div_i%3);
    always @(posedge clk) div12_q<=div12_rom[dx[11:2]];
    always @(posedge clk or posedge rst)
        if(rst) dx_low_a<=0;else dx_low_a<=dx[1:0];
    wire [3:0] row=dy[7:4];
    wire [3:0] gy=dy[3:0];
    reg [3:0] focus_row;
    reg [4:0] focus_start,focus_end;
    reg [2:0] focus_col;
    always @(*) begin
        focus_col=0;focus_row=2;focus_start=0;focus_end=10;
        if(focus==1) begin focus_start=25;focus_end=30;end
        else if(focus>=2) begin
            if(focus<9) begin focus_row=4;focus_col=focus-2;end
            else if(focus<16) begin focus_row=5;focus_col=focus-9;end
            else if(focus<23) begin focus_row=6;focus_col=focus-16;end
            else begin focus_row=7;focus_col=focus-23;end
            focus_start={focus_col,2'b00};focus_end=focus_start+4;
            if(focus==28) begin focus_start=20;focus_end=27;end
            if(focus==29) begin focus_start=27;focus_end=32-1;end
        end
    end
    // DEL reaches column 31; handle its inclusive final column explicitly.
    // Editor highlighting does not need the banner selector or dx/12 divider.
    // Compare directly in pixels, keeping division out of its enable path.
    wire [10:0] editor_dx=x-(WIN_X0+2);
    wire [8:0] focus_left={focus_start,3'b000}+{focus_start,2'b00};
    wire [8:0] focus_right={focus_end,3'b000}+{focus_end,2'b00};
    wire highlight=txt && ((y-(WIN_Y0+2))>>4)==focus_row && editor_dx>=focus_left &&
                   ((focus==29) ? editor_dx<384:editor_dx<focus_right);
    function [7:0] static_char;
        input [3:0] row;input [4:0] col;
        begin
            static_char=8'd32;
            case(row)
            4'd0:case(col)
                5'd0:static_char=8'd84;
                5'd1:static_char=8'd69;
                5'd2:static_char=8'd88;
                5'd3:static_char=8'd84;
                5'd5:static_char=8'd79;
                5'd6:static_char=8'd83;
                5'd7:static_char=8'd68;
                default:static_char=8'd32;
            endcase
            4'd2:case(col)
                5'd0:static_char=8'd91;
                5'd1:static_char=8'd79;
                5'd2:static_char=8'd83;
                5'd3:static_char=8'd68;
                5'd4:static_char=8'd58;
                5'd6:static_char=8'd79;
                5'd7:static_char=8'd70;
                5'd8:static_char=8'd70;
                5'd9:static_char=8'd93;
                5'd25:static_char=8'd91;
                5'd26:static_char=8'd67;
                5'd27:static_char=8'd76;
                5'd28:static_char=8'd82;
                5'd29:static_char=8'd93;
                default:static_char=8'd32;
            endcase
            4'd7:case(col)
                5'd20:static_char=8'd91;
                5'd21:static_char=8'd83;
                5'd22:static_char=8'd80;
                5'd23:static_char=8'd65;
                5'd24:static_char=8'd67;
                5'd25:static_char=8'd69;
                5'd26:static_char=8'd93;
                5'd27:static_char=8'd91;
                5'd28:static_char=8'd68;
                5'd29:static_char=8'd69;
                5'd30:static_char=8'd76;
                5'd31:static_char=8'd93;
                default:static_char=8'd32;
            endcase
            4'd8:case(col)
                5'd0:static_char=8'd50;
                5'd1:static_char=8'd47;
                5'd2:static_char=8'd56;
                5'd3:static_char=8'd47;
                5'd4:static_char=8'd52;
                5'd5:static_char=8'd47;
                5'd6:static_char=8'd54;
                5'd8:static_char=8'd77;
                5'd9:static_char=8'd79;
                5'd10:static_char=8'd86;
                5'd11:static_char=8'd69;
                5'd13:static_char=8'd53;
                5'd15:static_char=8'd79;
                5'd16:static_char=8'd75;
                5'd18:static_char=8'd35;
                5'd20:static_char=8'd66;
                5'd21:static_char=8'd65;
                5'd22:static_char=8'd67;
                5'd23:static_char=8'd75;
                default:static_char=8'd32;
            endcase
            default:static_char=8'd32;
            endcase
        end
    endfunction
    function [7:0] editor_char;
        input [3:0] r;input [4:0] c;
        input [7:0] preview_character;
        input [`TEXT_OSD_LEN_W-1:0] visible_length;
        input scrolled,enabled;input [23:0] count;
        begin
            editor_char=static_char(r,c);
            case(r)
            0:begin
                if(c==24) editor_char=count[23:16];
                if(c==25) editor_char=count[15:8];
                if(c==26) editor_char=count[7:0];
                if(c==27) editor_char="/";
                if(c==28) editor_char="2";
                if(c==29) editor_char="5";
                if(c==30) editor_char="6";
            end
            1:begin
                editor_char=" ";
                if(c==0) editor_char=scrolled ? "<":"[";
                else if(c==31) editor_char="]";
                else if(c==visible_length+1'b1) editor_char="_";
                else if(c>=1 && c<=visible_length) editor_char=preview_character;
            end
            2:begin
                if(c==7 && enabled) editor_char="N";
                if(c==8 && enabled) editor_char=" ";
            end
            4,5,6:begin
                if(c<28 && c[1:0]==1) editor_char="A"+(r-4)*7+c[4:2];
            end
            7:begin
                if(c<20 && c[1:0]==1) editor_char="V"+c[4:2];
            end
            default:begin end
            endcase
        end
    endfunction
    wire [26:0] resource_pixel;
    wire [23:0] rgb_b=resource_pixel[23:0];
    resource_text_dsp_pipe2 u_pixel_pipe(.clk(clk),.rst(rst),.din({hs,vs,de,pix_in}),.q(resource_pixel));
    reg [23:0] rgb_c,rgb_d;
    reg [2:0] hs_pipe,vs_pipe,de_pipe;
    reg win_a,txt_a,line_a,high_a,win_b,txt_b,line_b,high_b,win_c,txt_c,line_c,high_c,win_d,txt_d,line_d,high_d;
    wire [8:0] col_a=div12_q[10:2];
    wire [3:0] gx_a={div12_q[1:0],dx_low_a};
    reg [3:0] row_a;
    reg [3:0] gy_a,gx_b,gy_b,gx_c,gy_c,gx_d,gy_d;
    reg [6:0] char_c;
    reg read_text_b;reg [7:0] literal_b;
    wire [1:0] coverage;
    // RAM reads alongside stage B; stage C consumes the synchronous byte.
    assign text_addr=line_a ? col_a[7:0]:preview_start[7:0]+col_a[7:0]-1'b1;
    always @(posedge clk or posedge rst) begin
        if(rst) begin
            rgb_c<=0;rgb_d<=0;hs_pipe<=0;vs_pipe<=0;de_pipe<=0;
            win_a<=0;txt_a<=0;line_a<=0;high_a<=0;win_b<=0;txt_b<=0;line_b<=0;high_b<=0;
            win_c<=0;txt_c<=0;line_c<=0;high_c<=0;win_d<=0;txt_d<=0;line_d<=0;high_d<=0;
            row_a<=0;gy_a<=0;gx_b<=0;gy_b<=0;gx_c<=0;gy_c<=0;gx_d<=0;gy_d<=0;char_c<=32;
            read_text_b<=0;literal_b<=32;
        end else begin
            rgb_c<=rgb_b;rgb_d<=rgb_c;
            // Precompute the glass layer from the same stage-C pixel that is
            // entering rgb_d. This keeps the external four-stage latency but
            // splits glass arithmetic from the final anti-aliased blend.
            // txt_c and line_c become txt_d and line_d on this edge.
            // The previous pixel's line_d/coverage still supplies the shadow.
            hs_pipe<={hs_pipe[1:0],resource_pixel[26]};vs_pipe<={vs_pipe[1:0],resource_pixel[25]};de_pipe<={de_pipe[1:0],resource_pixel[24]};
            win_a<=win;txt_a<=txt;line_a<=line;high_a<=highlight;
            win_b<=win_a;txt_b<=txt_a;line_b<=line_a;high_b<=high_a;
            win_c<=win_b;txt_c<=txt_b;line_c<=line_b;high_c<=high_b;
            win_d<=win_c;txt_d<=txt_c;line_d<=line_c;high_d<=high_c;
            row_a<=row;gy_a<=gy;gx_b<=gx_a;gy_b<=gy_a;gx_c<=gx_b;gy_c<=gy_b;gx_d<=gx_c;gy_d<=gy_c;
            read_text_b<=(line_a && col_a<text_len) ||
                         (txt_a && row_a==1 && col_a>=1 && col_a<=visible_len);
            literal_b<=txt_a ? editor_char(row_a,col_a[4:0],8'd32,visible_len,preview_start!=0,osd_enable,count_characters):8'd32;
            char_c<=read_text_b ? text_data[6:0]:literal_b[6:0];
        end
    end
    assign font_char=char_c;assign font_x=gx_c;assign font_y=gy_c;
    generate if(EXTERNAL_FONT) begin:shared_font
        assign coverage=font_alpha;
    end else begin:local_font
        font_rom u_font(.clk(clk),.char_code(font_char),.gx(font_x),.gy(font_y),.alpha(coverage));
    end endgenerate
    `include "font_blend.vh"
    function [7:0] glass_channel;
        input [7:0] src,tint;
        input [1:0] weight;
        reg [9:0] sum;
        begin
            case(weight)
            2'd2: sum=({2'b0,src}<<1)+({2'b0,tint}<<1);
            2'd3: sum=({2'b0,src}<<1)+{2'b0,src}+{2'b0,tint};
            default: sum={src,2'b00};
            endcase
            glass_channel=sum[9:2];
        end
    endfunction
    function [23:0] glass_rgb;
        input [23:0] src,tint;
        input [1:0] weight;
        begin
            glass_rgb={glass_channel(src[23:16],tint[23:16],weight),
                       glass_channel(src[15:8],tint[15:8],weight),
                       glass_channel(src[7:0],tint[7:0],weight)};
        end
    endfunction
    // Both text placements use the same foreground and coverage. Select
    // their background before one exact blend, preserving the output stage.
    reg [1:0] background_mode;
    always @(*) begin
      background_mode=txt_c ? (high_c ? 2'd2:2'd1):
                      ((line_d && coverage!=0) ? 2'd3:2'd0);
    end
    wire [15:0] background_r,background_g;
    wire [7:0] background_b;
    reg background_valid;
    always @(posedge clk or posedge rst) if(rst) background_valid<=0;else background_valid<=1;
    wire [23:0] glyph_bg_d=background_valid ? {background_r[7:0],background_g[15:8],background_b}:24'd0;
    resource_text_background_rg u_background_rg(.clk(clk),.addr({background_mode,rgb_c[23:16]}),
      .addr_b({background_mode,rgb_c[15:8]}),.q(background_r),.q_b(background_g));
    resource_text_background_b u_background_b(.clk(clk),.addr({background_mode,rgb_c[7:0]}),.q(background_b));
    wire [23:0] glyph_background=glyph_bg_d;
    // Exact AA table replaces the existing arithmetic register boundary.
    // The synchronous reads and the bypass RGB/control registers advance
    // together, so pixel latency and coverage alignment stay unchanged.
    wire [15:0] final_r,final_g;
    wire [7:0] final_b;
    reg final_valid;
    reg [23:0] rgb_e;
    reg win_e,txt_e,line_e;
    always @(posedge clk or posedge rst) begin
        if(rst) begin
            final_valid<=0;rgb_e<=0;win_e<=0;txt_e<=0;line_e<=0;
        end else begin
            final_valid<=1;rgb_e<=rgb_d;
            win_e<=win_d;txt_e<=txt_d;line_e<=line_d;
        end
    end
    resource_text_final_rg u_final_rg(.clk(clk),.addr({coverage,glyph_background[23:16]}),
        .addr_b({coverage,glyph_background[15:8]}),.q(final_r),.q_b(final_g));
    resource_text_final_b u_final_b(.clk(clk),.addr({coverage,glyph_background[7:0]}),.q(final_b));
    wire [23:0] glyph_rgb=final_valid ? {final_r[7:0],final_g[15:8],final_b}:24'd0;
    always @(*) begin
        pix_out=rgb_e;
        if(de_pipe[2]) begin
            if(win_e && !txt_e) pix_out=C_BORDER;
            else if(txt_e || line_e) pix_out=glyph_rgb;
        end
    end
    assign hs_out=hs_pipe[2];assign vs_out=vs_pipe[2];assign de_out=de_pipe[2];
endmodule

