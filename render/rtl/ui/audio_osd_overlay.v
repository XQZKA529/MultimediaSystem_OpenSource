//=============================================================================
// module : audio_osd_overlay
// 文件名 : rtl/ui/audio_osd_overlay.v
// 功  能 : 【音频播放 OSD 合成器】面板底板/边框 + 四个 painter 的优先级合成。
//
//  定位（"不做什么"和"做什么"一样重要）：
//    它**不知道** pos/total 是什么、不知道 level 从哪来、不做任何单位换算或时间
//    运算。它只做三件事：① 从 de/vs 重建坐标；② 把模型按几何分发到 4 个
//    painter；③ 按优先级把 painter 的"墨色代码"查表成 RGB 并 mux 到像素流上。
//    四个 painter 彼此无连线、无共享状态、无先后依赖。
//
//  ★★ 流水结构（2026-09-25 教训：纯组合版会黑屏，别改回去）★★
//    原实现是纯组合输出（与 ui_text_overlay 相同的相位约定），但
//    "坐标 → 四个 painter → 优先级 → 调色 → mux" 一整锥在 13.33ns 的
//    video_clk 里放不下（布线后实测 18.9ns，75MHz 域只做到 47.5MHz
//    ⇒ 整屏黑屏）。现在改为**内部一级流水**：
//      第 1 拍（组合）：坐标/几何判定 + 四个 painter 的 draw/ink 决策 → 寄存
//      第 2 拍（组合）：优先级 mux + 调色 + 与 pix_in 合成 → pix_out（仍组合，
//                       由末级 video_stream_reg 收口）
//    hs/vs/de/pix_in 同步延迟两拍（文本 painter 内部还有一级），输出相位严格对齐：
//      pix_out(N+2) = 对输入像素 N 的合成结果，de_out/vs_out/hs_out(N+2) =
//      输入流 N 的 de/vs/hs。**端到端流没有移位、没有错行。**
//    （若改回纯组合，屏幕黑屏；若去掉决策寄存只延迟输出，整幅画面错位 1 像素
//      且行尾出现对角剪切。）
//
//  ★ 坐标相位约定：与 ui_text_overlay 一致，用 **"de 无效即清零"**，使 x_cnt 与
//    pix_in 零延迟对齐。**不要**改成 error_overlay 的"de 上升沿清 0"。
//
//  ★ 优先级（画在最上面的赢）：边框 > 播放/暂停图标 > 节拍动画 > 时间文本 >
//    进度条 > 面板底色 > 直通。四个元素几何上不重叠，优先级只为边框和将来
//    调整几何时兜底。
//
//  与既有两层的关系：显示链为
//      rgb_base → error_overlay → ui_text_overlay →【本模块(+1 拍)】
//      → video_stream_reg → HDMI
//    本层在 error_overlay **下游**，不影响后者内部的 frame_black 全黑检测。
//=============================================================================
`include "../pkg/video_bmp_params.vh"
`include "../pkg/osd_model_bus.vh"
module audio_osd_overlay #(
    // 720p 默认值全部来自 rtl/pkg/video_bmp_params.vh（几何唯一出处）
    parameter [10:0] PANEL_X0 = `VBP_OSD_X0,
    parameter [10:0] PANEL_Y0 = `VBP_OSD_Y0,
    parameter [10:0] PANEL_W  = `VBP_OSD_W,
    parameter [10:0] PANEL_H  = `VBP_OSD_H,
    parameter [10:0] BORDER   = `VBP_OSD_BORDER,
    parameter [10:0] TXT_X    = `VBP_OSD_TXT_X,
    parameter [10:0] TXT_Y    = `VBP_OSD_TXT_Y,
    parameter integer TXT_SCALE = `VBP_OSD_TXT_SCALE,
    parameter [10:0] BAR_X0   = `VBP_OSD_BAR_X0,
    parameter [10:0] BAR_Y0   = `VBP_OSD_BAR_Y0,
    parameter integer BAR_W   = `VBP_OSD_BAR_W,
    parameter integer BAR_H   = `VBP_OSD_BAR_H,
    parameter [10:0] ANIM_X0  = `VBP_OSD_ANIM_X0,
    parameter [10:0] ANIM_Y0  = `VBP_OSD_ANIM_Y0,
    parameter integer ANIM_W  = `VBP_OSD_ANIM_W,
    parameter integer ANIM_H  = `VBP_OSD_ANIM_H,
    // 频谱柱几何（扩展频点：只改 video_bmp_params.vh 的三个宏）
    parameter integer NBANDS  = `VBP_OSD_BANDS,
    parameter integer BAND_W  = `VBP_OSD_BAND_W,
    parameter integer BAND_SH = `VBP_OSD_BAND_SH,
    parameter [10:0] ICON_X0  = `VBP_OSD_ICON_X0,
    parameter [10:0] ICON_Y0  = `VBP_OSD_ICON_Y0,
    parameter integer ICON_W  = `VBP_OSD_ICON_W,
    parameter integer ICON_H  = `VBP_OSD_ICON_H
)(
    input  wire        video_clk,
    input  wire        rst,               // 高有效，video 域
    input  wire        hs,                // 行同步（直通，随流延迟 1 拍）
    input  wire        vs,                // 与 de / pix_in 对齐的场同步
    input  wire        de,                // 与 pix_in 对齐的数据有效
    input  wire [23:0] pix_in,
    input  wire [`OSD_M_W-1:0] i_model,   // 来自 audio_osd_status（单向）
    output wire        hs_out,            // = hs 延迟 1 拍（与 pix_out 对齐）
    output wire        vs_out,            // = vs 延迟 1 拍
    output wire        de_out,            // = de 延迟 1 拍
    output wire [23:0] pix_out            // 合成像素（决策寄存后第 2 拍组合输出）
);

    // 调色板（全工程唯一一处；painter 只报墨色代码，不碰 RGB）
    localparam [23:0] C_PANEL_BG = 24'h14_17_1B;
    localparam [23:0] C_BORDER   = 24'hD6_DB_E1;


    //-------------------------------------------------------------------------
    // 从 de/vs 重建坐标（de 无效即清零 ⇒ 与 pix_in 零延迟对齐）
    //-------------------------------------------------------------------------
    reg [10:0] x_cnt, y_cnt;
    reg        de_d, vs_d;

    always @(posedge video_clk or posedge rst) begin
        if (rst) begin
            x_cnt <= 11'd0;
            y_cnt <= 11'd0;
            de_d  <= 1'b0;
            vs_d  <= 1'b0;
        end else begin
            de_d <= de;
            vs_d <= vs;

            if (vs & ~vs_d)
                y_cnt <= 11'd0;                   // 帧首
            else if (~de & de_d)
                y_cnt <= y_cnt + 11'd1;           // 行末

            if (~de)
                x_cnt <= 11'd0;                   // 行间/消隐
            else
                x_cnt <= x_cnt + 11'd1;
        end
    end

    //-------------------------------------------------------------------------
    // 模型字段分发
    //-------------------------------------------------------------------------
    wire [`OSD_TXT_W-1:0] m_txt    = i_model[`OSD_M_TXT];
    wire [9:0]            m_fillpx = i_model[`OSD_M_FILLPX];
    wire [1:0]            m_beat   = i_model[`OSD_M_BEAT];
    wire [`OSD_M_SPEC_W-1:0] m_spec = i_model[`OSD_M_SPEC];
    wire                  m_show   = i_model[`OSD_M_SHOW];
    wire                  m_paused = i_model[`OSD_M_PAUSED];
    wire                  m_blink1 = i_model[`OSD_M_BLINK1];

    //-------------------------------------------------------------------------
    // 面板判定 + 边框环
    // 局部坐标直接用无符号减法：越界会回绕成大值，而四个元素的最大
    // 宽度只有 340 ⇒ painter 内部的 (lx < W) 一定拒绝，无需额外门控。
    //-------------------------------------------------------------------------
    wire in_px = (x_cnt >= PANEL_X0) && (x_cnt <= (PANEL_X0 + PANEL_W - 11'd1));
    wire in_py = (y_cnt >= PANEL_Y0) && (y_cnt <= (PANEL_Y0 + PANEL_H - 11'd1));
    wire in_panel = in_px && in_py;

    wire in_inner_x = (x_cnt >= (PANEL_X0 + BORDER)) &&
                      (x_cnt <= (PANEL_X0 + PANEL_W - 11'd1 - BORDER));
    wire in_inner_y = (y_cnt >= (PANEL_Y0 + BORDER)) &&
                      (y_cnt <= (PANEL_Y0 + PANEL_H - 11'd1 - BORDER));
    wire in_border  = in_panel && !(in_inner_x && in_inner_y);

    //-------------------------------------------------------------------------
    // 局部坐标（各 painter 的左上角为原点）
    //-------------------------------------------------------------------------
    wire [10:0] lx_txt  = x_cnt - TXT_X;    wire [10:0] ly_txt  = y_cnt - TXT_Y;
    wire [10:0] lx_bar  = x_cnt - BAR_X0;   wire [10:0] ly_bar  = y_cnt - BAR_Y0;
    wire [10:0] lx_anim = x_cnt - ANIM_X0;  wire [10:0] ly_anim = y_cnt - ANIM_Y0;
    wire [10:0] lx_icon = x_cnt - ICON_X0;  wire [10:0] ly_icon = y_cnt - ICON_Y0;

    //-------------------------------------------------------------------------
    // 四个 painter（互不可见：各自的端口里没有对方的世界）
    //-------------------------------------------------------------------------
    wire [1:0] txt_alpha;
    wire        txt_draw;   wire [2:0] txt_ink;
    wire        bar_draw;   wire [2:0] bar_ink;
    wire        anim_draw;  wire [2:0] anim_ink;
    wire        icon_draw;  wire [2:0] icon_ink;

    reg [23:0] pix_d1;
    wire [7:0] glass_b;
    osd_paint_text #(
        .SCALE ( TXT_SCALE ),.SHARED_GLASS(1)
    ) u_txt (
        .clk  ( video_clk ),
        .rst  ( rst       ),
        .lx   ( lx_txt  ),
        .ly   ( ly_txt  ),
        .txt  ( m_txt   ),
        .draw ( txt_draw), .ink ( txt_ink ),.alpha(txt_alpha),.glass_blue_src(pix_d1[7:0]),.glass_blue_rgb(glass_b)
    );

    osd_paint_bar #(
        .BAR_W ( BAR_W ), .BAR_H ( BAR_H )
    ) u_bar (
        .lx      ( lx_bar  ),
        .ly      ( ly_bar  ),
        .fill_px ( m_fillpx),
        .draw    ( bar_draw), .ink ( bar_ink )
    );

    osd_paint_anim #(
        .REGISTERED(1),
        .NBANDS ( NBANDS  ),
        .BAND_W ( BAND_W  ),
        .BAND_SH( BAND_SH ),
        .ANIM_W ( ANIM_W ), .ANIM_H ( ANIM_H )
    ) u_anim (
        .clk(video_clk),.rst(rst),
        .lx         ( lx_anim ),
        .ly         ( ly_anim ),
        .heights    ( m_spec[NBANDS*5-1:0] ),
        .paused     ( m_paused),
        .draw       ( anim_draw ), .ink ( anim_ink )
    );

    osd_paint_icon #(
        .ICON_W ( ICON_W ), .ICON_H ( ICON_H )
    ) u_icon (
        .lx     ( lx_icon ),
        .ly     ( ly_icon ),
        .paused ( m_paused),
        .blink1 ( m_blink1),
        .draw   ( icon_draw ), .ink ( icon_ink )
    );

    //-------------------------------------------------------------------------
    // ★ 两级对齐寄存：文本 painter 内部自带 1 级（决策共 2 拍后有效）；
    //   text/anim 内部各有 1 拍；bar/icon 用 d1 补齐；全流延迟 2 拍。
    //   （锥被切成三段：坐标+几何 / 文本解码 / 调色+合成 —— 13.33ns 内放得下）
    //-------------------------------------------------------------------------
    reg        hs_d1, vs_d1, de_d1;

    reg        bar_draw_d1;  reg [2:0] bar_ink_d1;
    reg        icon_draw_d1; reg [2:0] icon_ink_d1;

    reg        show_d1, in_panel_d1, in_border_d1;
    reg        show_r;
    reg        in_panel_r, in_border_r;
    reg [1:0] txt_alpha_r;
    reg        txt_draw_r;  reg [2:0] txt_ink_r;
    reg        bar_draw_r;  reg [2:0] bar_ink_r;
    reg        anim_draw_r; reg [2:0] anim_ink_r;
    reg        icon_draw_r; reg [2:0] icon_ink_r;
    reg        hs_r, vs_r, de_r;
    reg [23:0] pix_r;

    always @(posedge video_clk or posedge rst) begin
        if (rst) begin
            hs_d1 <= 1'b0; vs_d1 <= 1'b0; de_d1 <= 1'b0; pix_d1 <= 24'd0;
            bar_draw_d1  <= 1'b0; bar_ink_d1  <= 3'd0;
            icon_draw_d1 <= 1'b0; icon_ink_d1 <= 3'd0;
            show_d1     <= 1'b0; in_panel_d1 <= 1'b0; in_border_d1 <= 1'b0;
            show_r      <= 1'b0;
            in_panel_r  <= 1'b0;
            in_border_r <= 1'b0;
            txt_alpha_r <= 0;txt_draw_r  <= 1'b0; txt_ink_r  <= 3'd0;
            bar_draw_r  <= 1'b0; bar_ink_r  <= 3'd0;
            anim_draw_r <= 1'b0; anim_ink_r <= 3'd0;
            icon_draw_r <= 1'b0; icon_ink_r <= 3'd0;
            hs_r <= 1'b0; vs_r <= 1'b0; de_r <= 1'b0;
            pix_r <= 24'd0;
        end else begin
            // +1 拍
            hs_d1 <= hs; vs_d1 <= vs; de_d1 <= de; pix_d1 <= pix_in;
            bar_draw_d1  <= bar_draw;  bar_ink_d1  <= bar_ink;
            icon_draw_d1 <= icon_draw; icon_ink_d1 <= icon_ink;
            // +1 拍（几何判定：与 x_cnt 对齐的当前像素）
            show_d1     <= m_show;
            in_panel_d1 <= in_panel;
            in_border_d1<= in_border;
            // +2 拍（决策）
            show_r      <= show_d1;
            in_panel_r  <= in_panel_d1;
            in_border_r <= in_border_d1;
            txt_alpha_r <= txt_alpha;txt_draw_r  <= txt_draw;  txt_ink_r  <= txt_ink;   // 文本内部已 1 拍
            bar_draw_r  <= bar_draw_d1;  bar_ink_r  <= bar_ink_d1;
            anim_draw_r <= anim_draw; anim_ink_r <= anim_ink;
            icon_draw_r <= icon_draw_d1; icon_ink_r <= icon_ink_d1;
            hs_r <= hs_d1; vs_r <= vs_d1; de_r <= de_d1;
            pix_r <= pix_d1;
        end
    end

    assign hs_out = hs_r;
    assign vs_out = vs_r;
    assign de_out = de_r;

    //-------------------------------------------------------------------------
    // 墨色查表（唯一出处）
    //-------------------------------------------------------------------------
    function [23:0] ink_rgb;
        input [2:0] k;
        begin
            case (k)
            `OSD_INK_BORDER : ink_rgb = 24'hD6_DB_E1;
            `OSD_INK_TEXT   : ink_rgb = 24'hF5_F7_FA;
            `OSD_INK_TEXTDIM: ink_rgb = 24'hBB_C0_C7;
            `OSD_INK_TRACK  : ink_rgb = 24'h73_7A_84;
            `OSD_INK_FILL   : ink_rgb = 24'hF5_F7_FA;
            `OSD_INK_HEAD   : ink_rgb = 24'hFF_FF_FF;
            `OSD_INK_DIM    : ink_rgb = 24'h73_7A_84;
            default         : ink_rgb = 24'h00_00_00;
            endcase
        end
    endfunction

    //-------------------------------------------------------------------------
    // ★ 第 2 拍：合成（浅锥；关窗时逐像素直通，零开销路径）
    //    pix_r/hs_r/vs_r/de_r 与决策寄存同拍，故输出严格对齐。
    //-------------------------------------------------------------------------
    `include "font_blend.vh"
    // Same edge as pix_r: tint lookups consume pix_d1, preserving two clocks.
    wire [15:0] glass_r,glass_g;
    wire [23:0] glass_pixel={glass_r[7:0],glass_g[15:8],glass_b[7:0]};
    // White glass: 50% white body, 75% white top edge. Wiring only;
    // pix_r belongs to the same input sample as the registered painter decision.
    wire [23:0] spectrum_glass_body = {
        1'b1,pix_r[23:17],1'b1,pix_r[15:9],1'b1,pix_r[7:1]};
    wire [23:0] spectrum_glass_edge = {
        2'b11,pix_r[23:18],2'b11,pix_r[15:10],2'b11,pix_r[7:2]};
    resource_audio_glass_rg u_glass_rg(.clk(video_clk),.addr(pix_d1[23:16]),
      .addr_b(pix_d1[15:8]),.q(glass_r),.q_b(glass_g));
    assign pix_out = (show_r && anim_draw_r) ?
                         (anim_ink_r == `OSD_INK_HEAD ? spectrum_glass_edge :
                          spectrum_glass_body) :
                     (show_r && in_panel_r) ? (in_border_r   ? C_BORDER
                                             : icon_draw_r ? ink_rgb(icon_ink_r)
                                             : anim_draw_r ? ink_rgb(anim_ink_r)
                                             : txt_draw_r  ? font_blend(ink_rgb(txt_ink_r),C_PANEL_BG,txt_alpha_r)
                                             : bar_draw_r  ? ink_rgb(bar_ink_r)
                                             :               glass_pixel)
                                            : pix_r;

endmodule

