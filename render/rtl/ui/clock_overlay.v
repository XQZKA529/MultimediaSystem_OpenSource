// Final three-clock layer: coordinates/character -> synchronous glyph -> RGB.
// Its font request owns port B only in the top clock or local editor regions.
module clock_overlay #(parameter FRAME_DIGITS=0)(
    input wire clk,rst,hs,vs,de,input wire [23:0] rgb_in,
    input wire [47:0] live_digits,draft_digits,input wire [2:0] focus,input wire editing,
    output wire font_request,output wire [6:0] font_char,output wire [3:0] font_x,font_y,
    input wire [1:0] font_alpha,
    output reg hs_out,vs_out,de_out,output wire [23:0] rgb_out
);
    reg [10:0] x,y;reg de_d,vs_d;
    always @(posedge clk or posedge rst) begin
        if(rst) begin x<=0;y<=0;de_d<=0;vs_d<=0;end
        else begin de_d<=de;vs_d<=vs;
            if(vs && !vs_d) y<=0;else if(!de && de_d) y<=y+1'b1;
            if(!de) x<=0;else x<=x+1'b1;
        end
    end
    wire plate=de && x>=8 && x<144 && y>=8 && y<60;
    wire date_line=de && x>=16 && x<136 && y>=16 && y<32;
    wire time_line=de && x>=16 && x<112 && y>=36 && y<52;
    wire card=de && editing && x>=446 && x<834 && y>=286 && y<434;
    wire editor_text=card && x>=448 && x<832 && y>=288 && y<432;
    wire text=date_line || time_line || editor_text;
    wire [8:0] dx=editor_text ? x-11'd448:x-11'd16;
    wire [7:0] dy=editor_text ? y-11'd288:time_line ? y-11'd36:y-11'd16;
    // Fixed compare/subtract network, no multiplier/divider in pixel coordinates.
    function [8:0] character_position;
        input [8:0] v;reg [8:0] rem;reg [4:0] col;
        begin rem=v;col=0;
            if(rem>=192) begin rem=rem-9'd192;col=col+5'd16;end
            if(rem>=96) begin rem=rem-9'd96;col=col+5'd8;end
            if(rem>=48) begin rem=rem-9'd48;col=col+5'd4;end
            if(rem>=24) begin rem=rem-9'd24;col=col+5'd2;end
            if(rem>=12) begin rem=rem-9'd12;col=col+5'd1;end
            character_position={col,rem[3:0]};
        end
    endfunction
    wire [8:0] position=character_position(dx);
    wire [4:0] col=position[8:4];wire [3:0] row=dy[7:4];
    reg [6:0] ch;reg [47:0] label;reg [7:0] pair;
    always @(*) begin
        ch=32;label=0;pair=0;
        if(date_line) case(col)
            0:ch="2";1:ch="0";2:ch="0"+live_digits[47:44];3:ch="0"+live_digits[43:40];
            4,7:ch="-";5:ch="0"+live_digits[39:36];6:ch="0"+live_digits[35:32];
            8:ch="0"+live_digits[31:28];9:ch="0"+live_digits[27:24];default:ch=32;
        endcase
        else if(time_line) case(col)
            0:ch="0"+live_digits[23:20];1:ch="0"+live_digits[19:16];2,5:ch=":";
            3:ch="0"+live_digits[15:12];4:ch="0"+live_digits[11:8];
            6:ch="0"+live_digits[7:4];7:ch="0"+live_digits[3:0];default:ch=32;
        endcase
        else if(editor_text) begin
            case(row)
                0:label="CLOCK ";1:begin label="YEAR  ";pair=draft_digits[47:40];end
                2:begin label="MONTH ";pair=draft_digits[39:32];end
                3:begin label="DAY   ";pair=draft_digits[31:24];end
                4:begin label="HOUR  ";pair=draft_digits[23:16];end
                5:begin label="MINUTE";pair=draft_digits[15:8];end
                6:begin label="SECOND";pair=draft_digits[7:0];end
                7:label="APPLY ";default:label=0;
            endcase
            if(col>=1 && col<=6) case(col)
                1:ch=label[47:40];2:ch=label[39:32];3:ch=label[31:24];
                4:ch=label[23:16];5:ch=label[15:8];6:ch=label[7:0];
            endcase
            if(row>=1 && row<=6) begin
                if(row==1) case(col) 16:ch="2";17:ch="0";18:ch="0"+pair[7:4];19:ch="0"+pair[3:0];endcase
                else case(col) 16:ch="0"+pair[7:4];17:ch="0"+pair[3:0];endcase
            end
            if(row==8) case(col)
                0:ch="2";1:ch="/";2:ch="8";4:ch="M";5:ch="O";6:ch="V";7:ch="E";
                9:ch="4";10:ch="/";11:ch="6";13:ch="-";14:ch="/";15:ch="+";
                17:ch="5";19:ch="A";20:ch="P";21:ch="P";22:ch="L";23:ch="Y";
                25:ch="#";27:ch="B";28:ch="A";29:ch="C";30:ch="K";
                default:ch=32;
            endcase
        end
    end
    wire highlight=editor_text && row=={1'b0,focus}+4'd1;
    wire border=(plate && (x==8 || x==143 || y==8 || y==59)) ||
                (card && (x==446 || x==833 || y==286 || y==433));
    reg [6:0] char_a;reg [3:0] gx_a,gy_a;
    reg request_a,panel_a,panel_b,text_a,text_b,high_a,high_b,border_a,border_b;
    wire [26:0] resource_pixel;
    wire [23:0] rgb_b=resource_pixel[23:0];
    resource_clock_dsp_pipe2 u_pixel_pipe(.clk(clk),.rst(rst),.din({hs,vs,de,rgb_in}),.q(resource_pixel));
    wire [15:0] character_descriptor;
    wire [1:0] character_kind=editor_text ? 2'd2:time_line ? 2'd1:2'd0;
    resource_clock_characters u_characters(.clk(clk),.addr({character_kind,row,col}),.addr_b(11'd0),.q(character_descriptor),.q_b());
    wire [95:0] calendar_digits={live_digits,draft_digits};
    wire [3:0] selected_digit=calendar_digits[95-{character_descriptor[4:0],2'b00} -: 4];
    wire [6:0] table_character=character_descriptor[15] ? 7'd48+selected_digit:character_descriptor[6:0];
    assign font_char=FRAME_DIGITS ? (request_a ? table_character:7'd32):char_a;assign font_x=gx_a;assign font_y=gy_a;assign font_request=request_a;
    function [23:0] glass;
        input [23:0] src;
        begin glass={1'b0,src[23:17],1'b0,src[15:9],1'b0,src[7:1]};end
    endfunction

    reg [23:0] background;
    always @(*) begin
        background=glass(rgb_b);
        if(high_b) background={2'd0,rgb_b[23:18],2'd0,rgb_b[15:10],2'd0,rgb_b[7:2]}+24'h404040;
    end
    always @(posedge clk or posedge rst) begin
        if(rst) begin char_a<=32;gx_a<=0;gy_a<=0;request_a<=0;panel_a<=0;panel_b<=0;
            text_a<=0;text_b<=0;high_a<=0;high_b<=0;border_a<=0;border_b<=0;
            hs_out<=0;vs_out<=0;de_out<=0;end
        else begin
            char_a<=text ? ch:7'd32;gx_a<=position[3:0];gy_a<=dy[3:0];request_a<=text;
            panel_a<=plate || card;panel_b<=panel_a;text_a<=text;text_b<=text_a;
            high_a<=highlight;high_b<=high_a;border_a<=border;border_b<=border_a;
            
            hs_out<=resource_pixel[26];vs_out<=resource_pixel[25];de_out<=resource_pixel[24];
        end
    end
    reg [23:0] palette_src;
    reg [1:0] palette_alpha;
    always @(*) begin
      palette_src=rgb_b;palette_alpha=0;
      if(resource_pixel[24] && panel_b) begin
        if(border_b) palette_src=24'h949494;
        else if(text_b) begin palette_src=background;palette_alpha=font_alpha;end
        else palette_src=glass(rgb_b);
      end
    end
    wire [23:0] palette_rgb;
    reg palette_valid;
    always @(posedge clk or posedge rst) if(rst) palette_valid<=0;else palette_valid<=1;
    assign rgb_out=palette_valid ? palette_rgb:24'd0;
    resource_clock_palette u_rg(.clk(clk),.a({palette_alpha,palette_src[23:16]}),
      .b({palette_alpha,palette_src[15:8]}),.qa(palette_rgb[23:16]),.qb(palette_rgb[15:8]));
    resource_clock_palette u_b(.clk(clk),.a({palette_alpha,palette_src[7:0]}),
      .b(10'd0),.qa(palette_rgb[7:0]),.qb());

endmodule

