// Highest-priority, frame-atomic local alarm display. Three equal stream stages.
// Coordinate arithmetic, shape/glyph preparation and final RGB are separated.
// FRAME_TIMESTAMPS reuses the frame-committed CDC registers in production.
// Standalone callers can keep the default local frame latch.
module emergency_overlay #(parameter FRAME_TIMESTAMPS=0)(
    input wire clk,rst,hs,vs,de,input wire [23:0] rgb_in,
    input wire enable,input wire [2:0] sources,input wire [8:0] groups,
    input wire [143:0] timestamps,
    output reg hs_out,vs_out,de_out,output reg [23:0] rgb_out,output wire frame_active
);
    reg [10:0] x,y;
    reg de_d,vs_d,active;
    assign frame_active=active;
    reg [2:0] frame_sources;
    reg [8:0] frame_groups;
    reg [47:0] frame_text;
    wire [143:0] frame_timestamps;
    generate if(FRAME_TIMESTAMPS) begin
        assign frame_timestamps=timestamps;
    end else begin
        reg [143:0] local_timestamps;
        reg local_vs;
        always @(posedge clk or posedge rst) begin
            if(rst) begin local_timestamps<=0;local_vs<=0;end
            else begin local_vs<=vs;if(!vs && local_vs) local_timestamps<=timestamps;end
        end
        assign frame_timestamps=local_timestamps;
    end endgenerate
    reg [5:0] frame_order;
    wire combined=frame_sources[2] && |frame_sources[1:0];
    wire [10:0] cy=combined ? 11'd440:11'd360;
    wire [10:0] top_y=combined ? 11'd100:11'd160;
    wire [10:0] text_left=11'd640-({7'd0,frame_text[47:44]}<<3);
    reg [10:0] x1,dy1,dx1,ty1,text_x1,text_y1;
    reg combined1;
    wire [28:0] resource_pixel;
    reg [2:0] sources1;
    reg [7:0] character1;


    reg shaft2,left_bound2,right_bound2,warning_bound2,base2,mark2;
    reg [8:0] tri_width2,twice_dx2;
    reg [7:0] slope2,left_distance2,right_distance2;
    wire [15:0] glyph_word;
    reg glyph_valid,glyph_odd;
    wire [4:0] glyph2=!glyph_valid ? 5'd0:(glyph_odd ? glyph_word[9:5]:glyph_word[4:0]);
    resource_emergency_pair_rom u_glyph(.clk(clk),
      .addr({character1,text_y1[4:2]}),.addr_b(11'd0),.q(glyph_word),.q_b());
    reg [2:0] column2;
    wire text_bound2=resource_pixel[27],active2=resource_pixel[28];
    wire hs2=resource_pixel[26],vs2=resource_pixel[25],de2=resource_pixel[24];
    wire [23:0] rgb2=resource_pixel[23:0];
    wire [10:0] head_start=combined1 ? 11'd840:11'd800;
    wire [10:0] left_end=combined1 ? 11'd440:11'd480;
    wire time_area=y>=612;
    wire [10:0] tx=time_area ? x-11'd464:x-text_left;
    wire [10:0] ty=time_area ? y-11'd612:y-11'd580;
    wire [1:0] line_index=ty[6:5];
    wire [1:0] source_id=line_index==0 ? frame_order[1:0]:
        line_index==1 ? frame_order[3:2]:frame_order[5:4];
    wire [47:0] line_digits=source_id==0 ? frame_timestamps[47:0]:
        source_id==1 ? frame_timestamps[95:48]:frame_timestamps[143:96];
    reg [7:0] character;
    always @(*) begin
        character=32;
        if(!time_area) case(frame_text[tx[7:4]*4 +: 4])
            1:character="B";2:character="0";3:character="1";4:character="C";
            5:character=127;6:character="=";default:character=32;
        endcase
        else case(tx[8:4])
            0:character=source_id==2 ? "C":"B";
            1:character=source_id==2 ? 8'd32:(source_id==0 ? "0":"1");
            3:character="2";4:character="0";
            5:character="0"+line_digits[47:44];6:character="0"+line_digits[43:40];
            7,10:character="-";
            8:character="0"+line_digits[39:36];9:character="0"+line_digits[35:32];
            11:character="0"+line_digits[31:28];12:character="0"+line_digits[27:24];
            14:character="0"+line_digits[23:20];15:character="0"+line_digits[19:16];
            16,19:character=":";
            17:character="0"+line_digits[15:12];18:character="0"+line_digits[11:8];
            20:character="0"+line_digits[7:4];21:character="0"+line_digits[3:0];
            default:character=32;
        endcase
    end
    wire text_bound=time_area ? (y<700 && ty[4:0]<24 && source_id!=3 && tx<352):
        (ty<24 && tx<({7'd0,frame_text[47:44]}<<4));
    wire arrow=shaft2 || (left_bound2 && left_distance2>slope2) ||
        (right_bound2 && right_distance2>slope2);
    wire triangle=tri_width2>=twice_dx2 && (tri_width2-twice_dx2<12 || base2);
    wire warning=warning_bound2 && (triangle || mark2);
    wire text_pixel=text_bound2 && column2>=1 && column2<=5 && glyph2[5-column2];
    // InputREG + OutputREG replace exactly the original first two stages.
    resource_emergency_dsp_pipe2 u_pixel_pipe(.clk(clk),.rst(rst),
      .din({active,text_bound,hs,vs,de,rgb_in}),.q(resource_pixel));
    function [47:0] layout;
        input [8:0] g;
        begin case(g)
            9'h001: layout=48'h200000000021;
            9'h002: layout=48'h200000000031;
            9'h003: layout=48'h700003106021;
            9'h004: layout=48'h100000000004;
            9'h005: layout=48'h600000406021;
            9'h006: layout=48'h600000406031;
            9'h007: layout=48'hb40603106021;
            9'h00a: layout=48'h700002105031;
            9'h00c: layout=48'h600000210504;
            9'h00e: layout=48'hb21050406031;
            9'h011: layout=48'h700003105021;
            9'h014: layout=48'h600000310504;
            9'h015: layout=48'hb31050406021;
            9'h01c: layout=48'hb31060210504;
            9'h021: layout=48'h600000405021;
            9'h022: layout=48'h600000405031;
            9'h023: layout=48'hb40503106021;
            9'h02a: layout=48'hb40602105031;
            9'h031: layout=48'hb40603105021;
            9'h054: layout=48'hb21050310504;
            9'h062: layout=48'hb21050405031;
            9'h08c: layout=48'hb31050210504;
            9'h0a1: layout=48'hb31050405021;
            9'h10a: layout=48'hb40502105031;
            9'h111: layout=48'hb40503105021;
            default: layout=0;
        endcase end
    endfunction
    // Row indices are precomputed once per frame, in chronological group order.
    function [5:0] order_layout;
        input [8:0] g;
        begin case(g)
            9'h001: order_layout=6'h3c;
            9'h002: order_layout=6'h3d;
            9'h003: order_layout=6'h34;
            9'h004: order_layout=6'h3e;
            9'h005: order_layout=6'h38;
            9'h006: order_layout=6'h39;
            9'h007: order_layout=6'h24;
            9'h00a: order_layout=6'h31;
            9'h00c: order_layout=6'h32;
            9'h00e: order_layout=6'h09;
            9'h011: order_layout=6'h34;
            9'h014: order_layout=6'h36;
            9'h015: order_layout=6'h18;
            9'h01c: order_layout=6'h12;
            9'h021: order_layout=6'h38;
            9'h022: order_layout=6'h39;
            9'h023: order_layout=6'h24;
            9'h02a: order_layout=6'h21;
            9'h031: order_layout=6'h24;
            9'h054: order_layout=6'h06;
            9'h062: order_layout=6'h09;
            9'h08c: order_layout=6'h12;
            9'h0a1: order_layout=6'h18;
            9'h10a: order_layout=6'h21;
            9'h111: order_layout=6'h24;
            default:order_layout=6'h3f;
        endcase end
    endfunction

    always @(posedge clk or posedge rst) begin
        if(rst) begin
            x<=0;y<=0;de_d<=0;vs_d<=0;active<=0;frame_sources<=0;frame_groups<=0;frame_text<=0;frame_order<=63;
            x1<=0;dy1<=0;dx1<=0;ty1<=0;text_x1<=0;text_y1<=0;combined1<=0;sources1<=0;character1<=32;
            
            shaft2<=0;left_bound2<=0;right_bound2<=0;warning_bound2<=0;base2<=0;mark2<=0;
            tri_width2<=0;twice_dx2<=0;slope2<=0;left_distance2<=0;right_distance2<=0;
            glyph_valid<=0;glyph_odd<=0;column2<=0;
            hs_out<=0;vs_out<=0;de_out<=0;rgb_out<=0;
        end else begin
            de_d<=de;vs_d<=vs;
            if(vs && !vs_d) y<=0;else if(!de && de_d) y<=y+1'b1;
            if(!vs && vs_d) begin
                active<=enable;frame_sources<=sources;frame_groups<=groups;frame_text<=layout(groups);
                frame_order<=order_layout(groups);
            end
            if(!de) x<=0;else x<=x+1'b1;
            // Stage 1: local coordinates and their matching frame configuration.
            x1<=x;dy1<=y>=cy ? y-cy:cy-y;dx1<=x>=640 ? x-11'd640:11'd640-x;
            ty1<=y-top_y;text_x1<=tx;text_y1<={6'd0,ty[4:0]};
            combined1<=combined;sources1<=frame_sources;character1<=character;
            
            // Stage 2: bounded shape comparisons and prepared glyph row.
            shaft2<=(|sources1[1:0]) && x1>=(sources1[0] ? left_end:11'd240) &&
                x1<(sources1[1] ? head_start:11'd1040) && dy1<(combined1 ? 40:64);
            left_bound2<=sources1[0] && x1>=240 && x1<left_end && dy1<(combined1 ? 100:160);
            right_bound2<=sources1[1] && x1>=head_start && x1<1040 && dy1<(combined1 ? 100:160);
            slope2<=combined1 ? (dy1<<1):dy1+(dy1>>1);
            left_distance2<=x1-11'd240;right_distance2<=11'd1040-x1;
            tri_width2<=combined1 ? ({1'b0,ty1}+({1'b0,ty1}>>2)):
                ({1'b0,ty1}+({1'b0,ty1}>>3)+({1'b0,ty1}>>4));
            twice_dx2<={dx1,1'b0};warning_bound2<=sources1[2] && ty1<(combined1 ? 200:340) && dx1<256;
            base2<=ty1>=(combined1 ? 192:332);
            mark2<=dx1<(combined1 ? 8:12) &&
                ((ty1>=(combined1 ? 45:70) && ty1<(combined1 ? 130:230)) ||
                 (ty1>=(combined1 ? 154:270) && ty1<(combined1 ? 172:292)));
            glyph_valid<=1;glyph_odd<=text_y1[1];column2<=text_x1[3:1];
            
            
            // Stage 3: RGB and every stream control incur exactly three clocks.
            hs_out<=hs2;vs_out<=vs2;de_out<=de2;
            if(active2) rgb_out<=!de2 ? 24'd0:(text_pixel ? 24'hffffff:((arrow || warning) ? 24'hff0000:24'd0));
            else rgb_out<=rgb2;
        end
    end
endmodule

